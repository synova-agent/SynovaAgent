def parse_override(path: Path) -> Dict[str, Any]:
    """board-override.yaml 手动薄层 (生成器只读, git 无法表达的事实唯一入口)。

    支持 YAML 子集: 注释 (#), 段头 (priorities:/statuses:/blocked:/backlog:/decisions:),
    列表项 (- Dxxx: text | - text)。
    @input  — path: docs/synova/coverage/board-override.yaml
    @output — {priorities: {D#: str}, statuses: {D#: str}, blocked: {D#: str},
               backlog: [str], decisions: [str]}; 文件缺失 -> {}
    """
    if not path.exists():
        return {}
    sections: Dict[str, Any] = {"priorities": {}, "statuses": {}, "blocked": {},
                                "backlog": [], "decisions": []}
    current: Optional[str] = None
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return {}
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"^([a-zA-Z_]+):\s*$", line)
        if m:
            current = m.group(1) if m.group(1) in sections else None
            continue
        if current and line.startswith("- "):
            item = line[2:].strip()
            dm = re.match(r"^(D\d+)\s*:\s*(.*)$", item, flags=re.IGNORECASE)
            if dm and current in ("priorities", "statuses", "blocked"):
                sections[current][dm.group(1).upper()] = dm.group(2).strip()
            else:
                sections[current].append(item)
    return sections


# dev doc 头部注释: "状态: dev doc | 2026-08-08 | 优先级 P1"
_DOC_STATUS_RE = re.compile(
    r"状态:\s*(.+?)\s*\|\s*(\d{4}-\d{2}-\d{2})\s*\|\s*优先级\s*(P\d)", re.IGNORECASE)


def parse_doc_header(text: str) -> Dict[str, str]:
    """dev doc 头部 HTML 注释解析: -> {status, date, priority}; 无匹配 -> {}。

    @input  — text: 文件内容
    @output — 头字段 dict; 缺失 -> {}
    """
    m = _DOC_STATUS_RE.search(text)
    if not m:
        return {}
    return {"status": m.group(1).strip(), "date": m.group(2), "priority": m.group(3).upper()}


def scan_dev_docs(dev_docs_dir: Path) -> List[Dict[str, Any]]:
    """docs/plans/codex/implementation/*.md 扫描: D#/标题/头状态; 按 D# 倒序。

    @input  — dev_docs_dir: implementation 目录
    @output — [{d_id, title, status, date, priority}]; 目录缺失 -> []
    """
    if not dev_docs_dir.exists():
        return []
    docs: List[Dict[str, Any]] = []
    for f in sorted(dev_docs_dir.glob("*.md")):
        m = re.search(r"(D\d+)", f.name)
        if not m:
            continue
        try:
            text = f.read_text(encoding="utf-8")
        except OSError:
            text = ""
        title = re.sub(r"^SYNOVA-IMPL-\s*", "", f.stem)
        title = re.sub(r"[-_]\d{8}$", "", title)
        info = parse_doc_header(text)
        docs.append({
            "d_id": m.group(1), "title": title,
            "status": info.get("status", ""), "date": info.get("date", ""),
            "priority": info.get("priority", ""),
        })
    docs.sort(key=lambda d: int(re.search(r"\d+", d["d_id"]).group(0)), reverse=True)
    return docs


def scan_briefs(briefs_dir: Path) -> Dict[str, Dict[str, Any]]:
    """.claude/task-briefs/*.md 扫描: {D#: {exists: True, title: 去前缀文件名}}。

    @input  — briefs_dir: task-briefs 目录
    @output — D# -> 元信息; 目录缺失 -> {}
    """
    if not briefs_dir.exists():
        return {}
    found: Dict[str, Dict[str, Any]] = {}
    for f in briefs_dir.glob("*.md"):
        m = re.search(r"(D\d+)", f.name)
        if not m:
            continue
        title = re.sub(r"^D\d+[\s_-]*", "", f.stem)
        found[m.group(1)] = {"exists": True, "title": title}
    return found


def build_tasks(dev_docs: List[Dict[str, Any]], briefs: Dict[str, Dict[str, Any]],
                commits: List[Dict[str, Any]], unpushed: Optional[Set[str]],
                override: Dict[str, Any]) -> List[Dict[str, Any]]:
    """任务并集 (dev docs + git 提交 + override), 每 D# 一行; 按 D# 倒序。

    @input  — dev_docs/briefs/commits/unpushed/override: 各数据源解析结果
    @output — [{d_id, title, status, priority, has_brief, doc, commit, pushed}]
    @degraded — unpushed=None -> pushed=None (未知, 渲染标'未知')
    """
    override = override or {}
    ovr_pri = override.get("priorities", {})
    ovr_status = override.get("statuses", {})
    ovr_blocked = override.get("blocked", {})

    # D# -> 最新提交 (git log 最新在前 -> 首条即最新)
    latest: Dict[str, Dict[str, Any]] = {}
    for c in commits:
        for d in c["d_ids"]:
            if d not in latest:
                latest[d] = c

    # backlog/decisions 中 D#: 标题一并提取 ("D331: git notes 独立任务" -> title)
    ovr_titles: Dict[str, str] = {}
    for item in override.get("backlog", []) + override.get("decisions", []):
        m = re.match(r"^(D\d+)\s*:\s*(.*)$", item, flags=re.IGNORECASE)
        if m:
            ovr_titles[m.group(1).upper()] = m.group(2).strip()

    d_ids = (set(latest) | {d["d_id"] for d in dev_docs}
             | set(ovr_pri) | set(ovr_status) | set(ovr_blocked) | set(ovr_titles))

    tasks: List[Dict[str, Any]] = []
    for d_id in sorted(d_ids,
                       key=lambda s: (int(re.search(r"\d+", s).group(0)), s), reverse=True):
        commit = latest.get(d_id)
        doc = next((d for d in dev_docs if d["d_id"] == d_id), None)
        brief = briefs.get(d_id)

        # 标题: override > dev doc > brief 文件名 > commit subject
        title = (ovr_titles.get(d_id) or ""
                 or (doc["title"] if doc else "")
                 or (brief["title"] if brief else "")
                 or (commit["subject"][:80] if commit else ""))
        title = re.sub(r"^D\d+\s*[-_:：]?\s*", "", title)

        # 状态: override > blocked > dev doc 头 > 派生 (中性 token, 渲染时按语言翻译)
        status = (ovr_status.get(d_id)
                  or ("🔴 blocked: %s" % ovr_blocked[d_id] if d_id in ovr_blocked else "")
                  or (doc["status"] if doc else "")
                  or ("STATE_COMMITTED" if commit else
                      ("STATE_BRIEF" if brief else "STATE_TODO")))
        priority = ovr_pri.get(d_id) or (doc["priority"] if doc else "")

        pushed: Optional[bool] = None
        if commit is not None:
            pushed = commit["hash"] not in unpushed if unpushed is not None else None

        tasks.append({
            "d_id": d_id, "title": title, "status": status, "priority": priority,
            "has_brief": bool(brief), "doc": doc or None, "commit": commit,
            "pushed": pushed,
        })
    return tasks


