# ─── 契约: 各数据源解析 (失败 -> 返回空 + 调用方 degraded 标注, 不抛异常) ──────

def run_git(root: Path, args: List[str], timeout: int = 20) -> Optional[str]:
    """执行 git 命令, 返回 stdout (去尾部空白); 失败/超时返回 None。

    @input  — root: 仓库目录; args: git 参数 (不含 'git')
    @output — stdout 文本 | None
    @degraded — 非零退出/OSError/超时 -> None (调用方标注 degraded)
    """
    try:
        r = subprocess.run(
            ["git", "-C", str(root), *args],
            capture_output=True, text=True, encoding="utf-8", errors="replace",
            timeout=timeout,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if r.returncode != 0:
        return None
    return r.stdout


