# CI 结论排序: failure 最差 -> success 最好
_CI_ORDER = {"failure": 0, "in_progress": 1, "cancelled": 2, "skipped": 3, "success": 4}
_CI_MARK = {"failure": "❌", "in_progress": "⏳", "cancelled": "➖", "skipped": "➖", "success": "✅"}


def task_ci_marks(tasks: List[Dict[str, Any]], runs: List[Dict[str, Any]]) -> Dict[str, str]:
    """每 D# 的 CI 结论标记: 按最新提交 headSha 匹配 gh run, 多工作流取最差。

    @input  — tasks: build_tasks 输出; runs: read_ci 输出
    @output — {D#: "✅"|"❌"|"⏳"|"➖"|"—"}
    @degraded — 无匹配 run / 无提交 -> "—"
    """
    marks: Dict[str, str] = {}
    for t in tasks:
        c = t.get("commit")
        if not c or not runs:
            marks[t["d_id"]] = "—"
            continue
        matches = [r for r in runs if r.get("headSha") == c["hash"]]
        if not matches:
            marks[t["d_id"]] = "—"
            continue
        worst = min(matches, key=lambda r: _CI_ORDER.get(r.get("conclusion", ""), 5))
        marks[t["d_id"]] = _CI_MARK.get(worst.get("conclusion", ""), "❓")
    return marks


def _pushed_mark(pushed: Optional[bool], ln: Dict[str, str]) -> str:
    """推送状态标记: True ✅ / False ❌ / None 未知 (不假绿不假红)"""
    if pushed is True:
        return ln["pushed_yes"]
    if pushed is False:
        return ln["pushed_no"]
    return ln["unknown"]


def render_auto(tasks: List[Dict[str, Any]], versions: List[Dict[str, str]],
                tags: List[str], ci: Dict[str, Any], audit: Dict[str, Any],
                sync: Tuple[Optional[int], Optional[int]], lang: str,
                vlog: Optional[List[Dict[str, str]]] = None) -> str:
    """渲染 AUTO 区 (含 marker): 任务状态 + 版本历史 + CI + 同步健康。

    @input  — tasks: build_tasks; versions: read_version_md; tags: git_tags;
              ci: read_ci; audit: read_audit; sync: (未推送数, 工作区变更数);
              lang: "cn"|"en"; vlog: read_version_log (可选, 默认无)
    @output — AUTO marker 之间的 Markdown (含 marker 本身)
    @degraded — ci/audit/sync 缺失 -> 段内逐项标注, 不伪造数字
    """
    ln = L10N.get(lang, L10N["cn"])
    parts: List[str] = [AUTO_START, ln["task_status"], ln["task_note"]]

    # ── 任务状态表 (D# | 任务 | 状态 | 提交 | 作者 | 日期 | 推送 | CI | 审计) ──
    ci_runs = ci.get("runs", [])
    marks = task_ci_marks(tasks, ci_runs)
    header = "| D# | %s | %s | %s | %s | %s | %s | %s | %s |" % (
        ln["task"], ln["status"], ln["commit"], ln["author"],
        ln["date"], ln["pushed"], ln["ci"], ln["audit"])
    sep = "|----|-----|------|------|------|------|:---:|:---:|:---:|"
    rows: List[str] = []
    for t in tasks:
        c = t["commit"]
        status_cell = t["status"]
        if status_cell == "STATE_COMMITTED":
            status_cell = ln["state_committed"]
        elif status_cell == "STATE_BRIEF":
            status_cell = ln["state_brief"]
        elif status_cell == "STATE_TODO":
            status_cell = ln["state_todo"]
        if t["priority"]:
            status_cell = "%s（%s）" % (status_cell, t["priority"])
        rows.append("| %s | %s | %s | %s | %s | %s | %s | %s | — |" % (
            t["d_id"],
            _md_cell(t["title"] or "—", 48),
            _md_cell(status_cell or "—", 40),
            c["short_hash"] if c else "—",
            _md_cell(c["author"] if c else "—", 20),
            c["date"] if c else ((t["doc"].get("date") if t["doc"] else None) or "—"),
            _pushed_mark(t["pushed"], ln),
            marks.get(t["d_id"], "—"),
        ))
    if not rows:
        rows.append("| — | %s | — | — | — | — | — | — | — |" % ln["empty_table"])
    parts.extend([header, sep] + rows)

    # 审计全局摘要 + degraded 标注
    if audit.get("data"):
        d = audit["data"]
        note = "%s: P0 %s / P1 %s / P2 %s @ %s" % (
            ln["audit_note"], d.get("p0Count", "?"), d.get("p1Count", "?"),
            d.get("p2Count", "?"), d.get("generatedAt", "?"))
    else:
        note = "%s: degraded: %s" % (ln["audit_note"], audit.get("degraded", "无数据"))
    parts.append("> " + note)

    # ── 版本历史 ──
    parts.append(ln["version_hist"])
    parts.append("> " + ln["version_note"])
    v_header = "| %s | %s | %s | %s |" % (ln["version"], ln["version_date"], ln["changes"], ln["tag"])
    v_sep = "|------|------------|------|:---:|"
    v_rows: List[str] = []
    for v in versions:
        tag_mark = "✅" if v["version"] in tags else "—"
        v_rows.append("| %s | %s | %s | %s |" % (
            v["version"], v["date"], _md_cell(v["title"] or "—", 60), tag_mark))
    if not v_rows:
        v_rows.append("| — | — | %s | — |" % ln["empty_version"])
    parts.extend([v_header, v_sep] + v_rows)
    if not tags:
        parts.append("> ⚠️ %s" % ln["tag_pending"])
    # version.log 最近 3 条 (时间精确, 运行时产物)
    for e in (vlog or [])[:3]:
        parts.append("- %s %s: %s" % (e["version"], e["time"], _md_cell(e["changes"] or "—", 60)))

    # ── CI 状态 ──
    parts.append(ln["ci_status"])
    if ci.get("degraded"):
        parts.append("> degraded: %s" % ci["degraded"])
    c_header = "| %s | %s | %s | %s | %s |" % (ln["run"], ln["workflow"], ln["run_status"],
                                               ln["conclusion"], ln["related_d"])
    c_sep = "|:---:|------|:---:|:---:|------|"
    c_rows: List[str] = []
    for i, r in enumerate(ci_runs, 1):
        d_ids = " ".join(sorted(set(re.findall(r"D\d+", r.get("displayTitle", "")))))
        c_rows.append("| %d | %s | %s | %s %s | %s |" % (
            i, _md_cell(r.get("workflowName", "—"), 30),
            r.get("status", "—"),
            _CI_MARK.get(r.get("conclusion", ""), "❓"), r.get("conclusion", "—"),
            d_ids or "—"))
    if not c_rows:
        c_rows.append("| — | %s | — | — | — |" % ln["empty_run"])
    parts.extend([c_header, c_sep] + c_rows)

    # ── 同步健康 (D323 预留) ──
    parts.append(ln["sync_health"])
    n_unpushed, n_porcelain = sync
    if n_unpushed is None:
        parts.append("- %s: 未知（origin 缺失或 git 失败 — degraded）" % ln["unpushed"])
    else:
        parts.append("- %s: %d（origin/<branch>..HEAD）" % (ln["unpushed"], n_unpushed))
    if n_porcelain is None:
        parts.append("- %s: 未知（git status 失败 — degraded）" % ln["porcelain"])
    else:
        parts.append("- %s: %d 个文件（git status --porcelain）" % (ln["porcelain"], n_porcelain))
    parts.append("> %s" % ln["sync_reserved"])

    parts.append(AUTO_END)
    return "\n".join(parts)


def _md_cell(text: str, max_len: int) -> str:
    """Markdown 单元格清洗: 去换行/管道符, 截断"""
    t = text.replace("|", "／").replace("\n", " ").strip()
    if len(t) > max_len:
        t = t[: max_len - 1] + "…"
    return t


def extract_manual(text: str) -> Optional[str]:
    """提取 MANUAL marker 之间内容 (逐字节, 仅剥 START 后一个换行分隔符)。

    @input  — text: 完整文件内容
    @output — 手动区内容 | None (marker 不完整 -> 首次运行标志)
    @degraded — marker 缺失 -> None (调用方走首次迁移)
    """
    start = text.find(MANUAL_START)
    end = text.find(MANUAL_END)
    if start == -1 or end == -1 or end <= start:
        return None
    inner = text[start + len(MANUAL_START):end]
    if inner.startswith("\n"):
        inner = inner[1:]
    return inner


def strip_auto_section(text: str) -> str:
    """剥离文件中的旧 AUTO 区 (自动区损坏/半迁移时用), 其余原样返回。

    @input  — text: 文件内容
    @output — 移除 AUTO marker 之间内容后的文本
    """
    m = re.search(re.escape(AUTO_START) + r".*?" + re.escape(AUTO_END), text, flags=re.DOTALL)
    if m:
        return text[: m.start()] + text[m.end():]
    return text


def strip_legacy_header(text: str) -> str:
    """首次运行: 剥离旧 frontmatter (---...---) + 首标题 (# ...), 其余原样。

    @input  — text: 无 marker 的旧文件内容
    @output — 待迁入 MANUAL 区的内容 (逐字节保留)
    """
    t = re.sub(r"^---\n.*?\n---\n", "", text, count=1, flags=re.DOTALL)
    t = re.sub(r"^#\s.*\n", "", t, count=1, flags=re.MULTILINE)
    return t


def render_dashboard(auto: str, manual: str, lang: str) -> str:
    """组装完整文件: frontmatter + 标题 + 生成声明 + AUTO 区 + MANUAL 区。

    @input  — auto: render_auto 输出 (含 marker); manual: extract_manual 输出;
              lang: "cn"|"en"
    @output — 完整 Markdown 文件内容
    @degraded — manual 为原始内容时同样逐字节保留
    """
    ln = L10N.get(lang, L10N["cn"])
    header = (
        "---\n"
        "title: \"%s\"\n" % ln["file_title"] +
        "status: \"%s\"\n" % ln["frontmatter_status"] +
        "---\n\n"
        "# %s\n\n" % ln["file_title"] +
        ln["notice"] + "\n"
    )
    # 循环稳定协议: extract_manual 剥 START 后 1 个 \n, 此处对称补回 —
    # 缺失则每次运行 manual 区前导空行被逐次吃掉 (内容漂移, 永不收敛)
    return (
        header
        + auto.rstrip("\n") + "\n"
        + MANUAL_START + "\n" + manual + MANUAL_END + "\n"
    )


def write_if_changed(path: Path, content: str) -> bool:
    """幂等写回: 内容与磁盘一致 -> 不写 (mtime 不变); 不一致 -> 写。

    @input  — path: 目标文件; content: 新内容
    @output — True=已写 / False=未写 (幂等)
    """
    try:
        if path.read_text(encoding="utf-8") == content:
            return False
    except OSError:
        pass
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def sync_health(root: Path, branch: str) -> Tuple[Optional[int], Optional[int]]:
    """同步健康: (未推送提交数, 工作区变更文件数)。

    @input  — root: 仓库目录; branch: 远端分支
    @output — (int|None, int|None); git 失败 -> None (degraded)
    """
    unpushed = git_unpushed(root, branch)
    n_unpushed = len(unpushed) if unpushed is not None else None
    out = run_git(root, ["status", "--porcelain"])
    n_porcelain: Optional[int] = None
    if out is not None:
        # 排除本生成器自己的输出文件 — 否则写文件本身改变计数 →
        # 自动区内容每次运行都不同 → 永远重写 (自引用漂移)
        lines = [l for l in out.splitlines() if l.strip()]
        lines = [l for l in lines if "docs/synova/DASHBOARD" not in l]
        n_porcelain = len(lines)
    return (n_unpushed, n_porcelain)


def render_one(path: Path, tasks: List[Dict[str, Any]], versions: List[Dict[str, str]],
               tags: List[str], ci: Dict[str, Any], audit: Dict[str, Any],
               sync: Tuple[Optional[int], Optional[int]], lang: str,
               vlog: Optional[List[Dict[str, str]]] = None) -> str:
    """单文件渲染: 首次运行旧内容整体迁入 MANUAL 区; 之后 MANUAL 区原样保留。

    @input  — path: DASHBOARD 文件; 其余同 render_auto; vlog: version.log 条目
    @output — 完整文件内容
    @degraded — 文件不可读 -> 手动区为空 (仍渲染 AUTO)
    """
    auto = render_auto(tasks, versions, tags, ci, audit, sync, lang, vlog)
    manual = ""
    if path.exists():
        try:
            existing = path.read_text(encoding="utf-8")
        except OSError:
            existing = ""
        extracted = extract_manual(existing)
        if extracted is not None:
            manual = extracted
        else:
            # 首次运行 / 手动区损坏: 剥离旧自动区 (若存在), 其余整体迁入手动区
            manual = strip_auto_section(strip_legacy_header(existing))
    return render_dashboard(auto, manual, lang)


def generate(root: Path, branch: str = DEFAULT_BRANCH, gh_bin: str = "gh",
             lang: str = "both", runner: Optional[Callable] = None,
             dry_run: bool = False) -> Dict[str, Any]:
    """编排: 采集 -> 合并 -> 渲染 -> 幂等写回 (CN + EN)。

    @input  — root: 仓库根目录; branch: 分支; gh_bin: gh 路径; lang: cn/en/both;
              runner: CI 测试注入; dry_run: 只算不写
    @output — {written: [路径], unchanged: [路径], degraded: [原因], tasks: n}
    @degraded — 各数据源失败 -> degraded 列表收集 (不阻断渲染)
    """
    dashboard_dir = root / "docs" / "synova"
    dev_docs_dir = root / "docs" / "plans" / "codex" / "implementation"
    briefs_dir = root / ".claude" / "task-briefs"
    version_md = root / ".codex" / "control-tower" / "VERSION.md"
    version_log = root / ".codex" / "control-tower" / "logs" / "version.log"
    audit_path = root / ".codex" / "audit" / "audit-result.json"
    override_path = root / "docs" / "synova" / "coverage" / "board-override.yaml"

    commits = git_log_d(root)
    unpushed = git_unpushed(root, branch)
    dev_docs = scan_dev_docs(dev_docs_dir)
    briefs = scan_briefs(briefs_dir)
    override = parse_override(override_path)
    tasks = build_tasks(dev_docs, briefs, commits, unpushed, override)
    versions = read_version_md(version_md)
    vlog = read_version_log(version_log)
    tags = git_tags(root)
    ci = read_ci(root, branch, CI_LIMIT, gh_bin, runner)
    audit = read_audit(audit_path)
    sync = sync_health(root, branch)

    degraded: List[str] = []
    for name, d in (("CI", ci.get("degraded")), ("审计", audit.get("degraded"))):
        if d:
            degraded.append("%s: %s" % (name, d))
    if unpushed is None:
        degraded.append("推送状态: origin/%s 缺失或 git 失败 — 推送列标'未知'" % branch)

    result: Dict[str, Any] = {"written": [], "unchanged": [], "degraded": degraded,
                              "tasks": len(tasks)}
    for fn, lng in (("DASHBOARD-CN.md", "cn"), ("DASHBOARD.md", "en")):
        if lang != "both" and lang != lng:
            continue
        path = dashboard_dir / fn
        content = render_one(path, tasks, versions, tags, ci, audit, sync, lng, vlog)
        if dry_run:
            result["unchanged"].append(str(path))
            continue
        if write_if_changed(path, content):
            result["written"].append(str(path))
        else:
            result["unchanged"].append(str(path))
    return result


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="仪表盘 git 化生成器 (D320) — 渲染 DASHBOARD-CN/EN 为 git 投影 + 薄手动层")
    parser.add_argument("--lang", choices=["cn", "en", "both"], default="both",
                        help="生成语言 (默认 both)")
    parser.add_argument("--root", default=str(PROJECT_ROOT),
                        help="仓库根目录 (测试注入用)")
    parser.add_argument("--branch", default=DEFAULT_BRANCH, help="主开发分支")
    parser.add_argument("--gh-bin", default="gh", help="gh 可执行路径")
    parser.add_argument("--dry-run", action="store_true", help="只计算不写文件")
    args = parser.parse_args(argv)

    result = generate(Path(args.root), branch=args.branch, gh_bin=args.gh_bin,
                      lang=args.lang, dry_run=args.dry_run)
    for d in result["degraded"]:
        print("[gen-task-board] [WARN] degraded: %s" % d, file=sys.stderr)
    if result["written"]:
        print("[gen-task-board] written: %s" % ", ".join(result["written"]))
    if result["unchanged"]:
        print("[gen-task-board] unchanged (幂等): %d 文件" % len(result["unchanged"]))
    print("[gen-task-board] tasks=%d" % result["tasks"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
