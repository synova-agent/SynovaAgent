def _alias_digest(name: str) -> str:
    """历史作者别名的加盐指纹（明文不入库；对应 client-name-patterns.json 同口径）。"""
    return hashlib.sha256(bytes.fromhex(_AUTHOR_ALIAS_SALT) + name.encode("utf-8")).hexdigest()


def normalize_author(author: str) -> str:
    """author 显示名归一 (品牌迁移 ClawOrg → Synova + 历史客户标识别名)。未命中则原样返回。

    两道查表: ① 明文品牌映射（ClawOrg 系，本身不含客户标识）
             ② **加盐哈希映射**（历史别名含客户标识 ⇒ 明文不入库，行为与旧明文 key 等价）
    未命中 → 原样返回（不臆改他人作者名）。
    """
    if author in AUTHOR_BRAND_MAP:
        return AUTHOR_BRAND_MAP[author]
    return _AUTHOR_ALIAS_MAP.get(_alias_digest(author), author)


def normalize_email(email: str) -> str:
    """email 显示名归一 (品牌迁移)。未命中则原样返回。"""
    return EMAIL_BRAND_MAP.get(email, email)


def git_log_d(root: Path) -> List[Dict[str, Any]]:
    """全历史 D# 提交 (git log --grep=D[0-9], BRE): 最新在前。

    @input  — root: 仓库目录
    @output — [{hash, short_hash, author, email, date, subject, d_ids}]
    @degraded — git 失败 -> [] (无 D# 行); 空仓库 -> []
    """
    out = run_git(root, ["log", "--grep=D[0-9]", "--format=" + _GIT_LOG_FMT, "--date=short"])
    if out is None:
        return []
    rows: List[Dict[str, Any]] = []
    for line in out.splitlines():
        parts = line.split("\x1f")
        if len(parts) < 5:
            continue
        h, author, email, date, subject = parts[0], parts[1], parts[2], parts[3], parts[4]
        d_ids = re.findall(r"D\d+", subject)
        if not d_ids:
            continue
        # 任务归属 = 首个 D#（conventional commit scope, 如 "chore(D316): ..."）。
        # 后置 D# 仅为提及（如 "…固化 D313-D316 协作教训"）— 不参与归属。
        d_ids = [d_ids[0]]
        rows.append({
            "hash": h, "short_hash": h[:7],
            "author": normalize_author(author), "email": normalize_email(email),
            "date": date, "subject": subject, "d_ids": d_ids,
        })
    return rows


def git_unpushed(root: Path, branch: str) -> Optional[Set[str]]:
    """origin/<branch>..HEAD 的未推送提交哈希集合。

    @input  — root: 仓库目录; branch: 远端分支名
    @output — Set[hash] | None
    @degraded — origin/<branch> 缺失 (未知) 或 git 失败 -> None
    """
    out = run_git(root, ["rev-list", "origin/%s..HEAD" % branch])
    if out is None:
        return None
    return {line.strip() for line in out.splitlines() if line.strip()}


def git_tags(root: Path) -> List[str]:
    """git tag 列表 (版本倒序); git 失败 -> [] (调用方标'版本待 tag')"""
    out = run_git(root, ["tag", "--sort=-v:refname"])
    if out is None:
        return []
    return [line.strip() for line in out.splitlines() if line.strip()]


# VERSION.md 条目: "## V4.6.2 (2026-08-07) — D317 修复（...）"
_VERSION_HEAD_RE = re.compile(r"^##\s+(V\d+\.\d+\.\d+)\s*\(([^)]*)\)\s*[—-]\s*(.*)$")


def read_version_md(path: Path) -> List[Dict[str, str]]:
    """VERSION.md 条目解析: [{version, date, title}], 文档顺序 (新在前)。

    @input  — path: .codex/control-tower/VERSION.md
    @output — 条目列表; 缺失/不可读 -> []
    """
    if not path.exists():
        return []
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return []
    entries: List[Dict[str, str]] = []
    for line in text.splitlines():
        m = _VERSION_HEAD_RE.match(line.strip())
        if m:
            entries.append({"version": m.group(1), "date": m.group(2), "title": m.group(3).strip()})
    return entries


def read_version_log(path: Path) -> List[Dict[str, str]]:
    """version.log JSON 追加流解析: [{version, changes, time}], 新在前。

    @input  — path: .codex/control-tower/logs/version.log
    @output — 条目列表; 缺失/不可读 -> []
    """
    if not path.exists():
        return []
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return []
    entries: List[Dict[str, str]] = []
    for line in reversed(lines):
        line = line.strip()
        if not line:
            continue
        try:
            d = json.loads(line)
        except json.JSONDecodeError:
            continue
        entries.append({
            "version": d.get("version", ""), "changes": d.get("changes", ""),
            "time": d.get("time", ""),
        })
    return entries


_CI_JSON_FIELDS = "workflowName,status,conclusion,headSha,displayTitle,createdAt"


def read_ci(root: Path, branch: str, limit: int = CI_LIMIT, gh_bin: str = "gh",
            runner: Optional[Callable] = None) -> Dict[str, Any]:
    """gh run list 最近 N 次 (branch 过滤): {runs: [...], degraded: str|None}。

    @input  — root: 仓库目录; branch: 分支; limit: 拉取量;
              gh_bin: gh 可执行路径; runner: 测试注入 (默认 subprocess.run)
    @output — {"runs": [run...], "degraded": None|str}
    @degraded — gh 缺失/非零退出/输出不可解析 -> runs=[] + degraded 原因 (不假 0)
    """
    cmd = [gh_bin, "run", "list", "--branch", branch, "--limit", str(limit),
           "--json", _CI_JSON_FIELDS]
    run = runner or subprocess.run
    try:
        r = run(cmd, capture_output=True, text=True, encoding="utf-8",
                errors="replace", timeout=30, cwd=str(root))
    except (OSError, subprocess.TimeoutExpired) as e:
        return {"runs": [], "degraded": "gh 不可用: %s" % e}
    if getattr(r, "returncode", 1) != 0:
        err = (getattr(r, "stderr", "") or "").strip()
        return {"runs": [], "degraded": "gh 不可用" + (": %s" % err[:120] if err else "")}
    try:
        runs = json.loads(getattr(r, "stdout", "") or "[]")
    except json.JSONDecodeError as e:
        return {"runs": [], "degraded": "gh 输出解析失败: %s" % e}
    return {"runs": runs if isinstance(runs, list) else [], "degraded": None}


